package oracle

import (
	"context"
	"os"
	"reflect"
	"strings"
	"testing"
	"time"

	coreconfig "github.com/lamassuiot/lamassuiot/v4/core/pkg/config"
	"github.com/lamassuiot/lamassuiot/v4/engines/storage/oracle/config"
	"gorm.io/gorm"
)

type dialectRecord struct {
	ID       int64 `gorm:"primaryKey;autoIncrement"`
	Title    string
	Content  string
	Metadata map[string]any `gorm:"serializer:json"`
}

type dialectChild struct {
	ID       int64 `gorm:"primaryKey;autoIncrement"`
	RecordID int64
	Record   dialectRecord `gorm:"foreignKey:RecordID"`
}

func (dialectChild) TableName() string { return "lamassu_dialect_child_test" }

func (dialectRecord) TableName() string { return "lamassu_dialect_test" }

func TestOracleGORM(t *testing.T) {
	connectString := os.Getenv("LAMASSU_TEST_ORACLE_CONNECT_STRING")
	if connectString == "" {
		t.Skip("LAMASSU_TEST_ORACLE_CONNECT_STRING is not set")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	pool, err := openDB(ctx, config.Config{ConnectString: connectString, Username: os.Getenv("LAMASSU_TEST_ORACLE_USERNAME"), Password: coreconfig.Password(os.Getenv("LAMASSU_TEST_ORACLE_PASSWORD"))})
	if err != nil {
		t.Fatal(err)
	}
	defer pool.Close()
	_, err = pool.ExecContext(ctx, `CREATE TABLE lamassu_dialect_test (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR2(200), content CLOB, metadata JSON)`)
	if err != nil {
		t.Fatal(err)
	}
	defer pool.ExecContext(context.Background(), "DROP TABLE lamassu_dialect_test PURGE")
	_, err = pool.ExecContext(ctx, `CREATE TABLE lamassu_dialect_child_test (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, record_id NUMBER NOT NULL REFERENCES lamassu_dialect_test(id))`)
	if err != nil {
		t.Fatal(err)
	}
	defer pool.ExecContext(context.Background(), "DROP TABLE lamassu_dialect_child_test PURGE")
	db, err := openGORM(pool)
	if err != nil {
		t.Fatal(err)
	}
	db = db.WithContext(ctx)
	first := dialectRecord{Title: "first", Content: strings.Repeat("large certificate ", 600), Metadata: map[string]any{"name": "example", "count": float64(3)}}
	if err := db.Create(&first).Error; err != nil {
		t.Fatal(err)
	}
	if first.ID == 0 {
		t.Fatal("generated ID was not returned")
	}
	second := dialectRecord{Title: "second", Content: "short", Metadata: map[string]any{"name": "second"}}
	if err := db.Create(&second).Error; err != nil {
		t.Fatal(err)
	}
	child := dialectChild{RecordID: second.ID}
	if err := db.Create(&child).Error; err != nil {
		t.Fatal(err)
	}
	var joined dialectChild
	if err := db.Joins("Record").First(&joined, "lamassu_dialect_child_test.id = ?", child.ID).Error; err != nil {
		t.Fatal(err)
	}
	if joined.Record.ID != second.ID || joined.Record.Title != second.Title {
		t.Fatalf("joined record mismatch: %+v", joined.Record)
	}
	var got dialectRecord
	if err := db.First(&got, "id = ?", first.ID).Error; err != nil {
		t.Fatal(err)
	}
	if got.ID != first.ID || got.Content != first.Content || !reflect.DeepEqual(got.Metadata, first.Metadata) {
		t.Fatalf("round trip mismatch: id=%d content length=%d metadata=%v", got.ID, len(got.Content), got.Metadata)
	}
	var page []dialectRecord
	if err := db.Order("id ASC").Limit(1).Offset(1).Find(&page).Error; err != nil {
		t.Fatal(err)
	}
	if len(page) != 1 || page[0].ID != second.ID {
		t.Fatalf("unexpected page: %+v", page)
	}
	if err := db.Model(&got).Update("title", "updated").Error; err != nil {
		t.Fatal(err)
	}
	err = db.Transaction(func(tx *gorm.DB) error {
		if err := tx.Model(&got).Update("title", "rolled back").Error; err != nil {
			return err
		}
		return gorm.ErrInvalidTransaction
	})
	if err != gorm.ErrInvalidTransaction {
		t.Fatalf("transaction error: %v", err)
	}
	var afterRollback dialectRecord
	if err := db.First(&afterRollback, "id = ?", first.ID).Error; err != nil || afterRollback.Title != "updated" {
		t.Fatalf("rollback result: title=%q error=%v", afterRollback.Title, err)
	}
	if err := db.Create(&[]dialectRecord{{Title: "bulk1"}, {Title: "bulk2"}}).Error; err == nil {
		t.Fatal("multi-row insert should fail explicitly")
	}
	if err := db.Delete(&got).Error; err != nil {
		t.Fatal(err)
	}
	if err := db.First(&dialectRecord{}, "id = ?", first.ID).Error; err != gorm.ErrRecordNotFound {
		t.Fatalf("expected not found, got %v", err)
	}
}
