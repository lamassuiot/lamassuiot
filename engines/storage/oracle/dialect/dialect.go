// Package dialect implements the Oracle SQL used by the storage engine.
// Schema changes are managed by versioned migrations, not GORM AutoMigrate.
package dialect

import (
	"database/sql"
	"fmt"
	"strconv"
	"strings"

	"gorm.io/gorm"
	"gorm.io/gorm/callbacks"
	"gorm.io/gorm/clause"
	"gorm.io/gorm/logger"
	"gorm.io/gorm/migrator"
	"gorm.io/gorm/schema"
)

type Dialector struct{ Conn *sql.DB }

func (Dialector) Name() string { return "oracle" }

func (d Dialector) Initialize(db *gorm.DB) error {
	if d.Conn == nil {
		return fmt.Errorf("oracle dialect requires a connection pool")
	}
	db.ConnPool = d.Conn
	callbacks.RegisterDefaultCallbacks(db, &callbacks.Config{CreateClauses: []string{"INSERT", "VALUES"}})
	db.ClauseBuilders["LIMIT"] = buildLimit
	if err := db.Callback().Create().Replace("gorm:create", create); err != nil {
		return err
	}
	return db.Callback().Query().Before("gorm:query").Register("oracle:map_columns", mapColumns)
}

func (d Dialector) Migrator(db *gorm.DB) gorm.Migrator {
	return migrator.Migrator{Config: migrator.Config{DB: db, Dialector: d}}
}

func (Dialector) DataTypeOf(field *schema.Field) string {
	switch field.DataType {
	case schema.Bool:
		return "NUMBER(1)"
	case schema.Int, schema.Uint:
		if field.AutoIncrement {
			return "NUMBER(19) GENERATED BY DEFAULT AS IDENTITY"
		}
		return "NUMBER(19)"
	case schema.Float:
		return "BINARY_DOUBLE"
	case schema.String:
		if field.Size > 0 && field.Size <= 4000 {
			return fmt.Sprintf("VARCHAR2(%d)", field.Size)
		}
		return "CLOB"
	case schema.Time:
		return "TIMESTAMP WITH TIME ZONE"
	case schema.Bytes:
		return "BLOB"
	default:
		return string(field.DataType)
	}
}

func (Dialector) DefaultValueOf(*schema.Field) clause.Expression { return clause.Expr{SQL: "DEFAULT"} }

func (Dialector) BindVarTo(w clause.Writer, stmt *gorm.Statement, _ interface{}) {
	w.WriteByte(':')
	w.WriteString(strconv.Itoa(len(stmt.Vars)))
}

// Oracle folds ordinary unquoted identifiers to uppercase. Quote that form so
// names such as SIZE remain usable and raw, unquoted predicates still resolve
// to the same objects. Dynamic column selection must still be allowlisted.
func (Dialector) QuoteTo(w clause.Writer, name string) {
	for i, part := range strings.Split(name, ".") {
		if i != 0 {
			w.WriteByte('.')
		}
		if part == "*" {
			w.WriteByte('*')
			continue
		}
		w.WriteByte('"')
		w.WriteString(strings.ReplaceAll(strings.ToUpper(part), `"`, `""`))
		w.WriteByte('"')
	}
}

func (Dialector) Explain(query string, vars ...interface{}) string {
	return logger.ExplainSQL(query, nil, "'", vars...)
}

func buildLimit(c clause.Clause, builder clause.Builder) {
	limit, ok := c.Expression.(clause.Limit)
	if !ok {
		return
	}
	if limit.Offset > 0 {
		builder.WriteString("OFFSET ")
		builder.AddVar(builder, limit.Offset)
		builder.WriteString(" ROWS")
	}
	if limit.Limit != nil && *limit.Limit >= 0 {
		if limit.Offset > 0 {
			builder.WriteByte(' ')
		}
		builder.WriteString("FETCH NEXT ")
		builder.AddVar(builder, *limit.Limit)
		builder.WriteString(" ROWS ONLY")
	}
}

func mapColumns(db *gorm.DB) {
	stmt := db.Statement
	if stmt == nil || stmt.Schema == nil {
		return
	}
	if stmt.ColumnMapping == nil {
		stmt.ColumnMapping = make(map[string]string)
	}
	for _, field := range stmt.Schema.Fields {
		if field.DBName != "" {
			stmt.ColumnMapping[strings.ToUpper(field.DBName)] = field.DBName
		}
	}
	// GORM names joined columns Relation__column; unquoted aliases arrive in
	// uppercase and must retain the relation's original Go name when scanned.
	for _, join := range stmt.Joins {
		current := stmt.Schema
		var parts []string
		for _, name := range strings.Split(join.Name, ".") {
			rel, ok := current.Relationships.Relations[name]
			if !ok {
				break
			}
			parts = append(parts, rel.Name)
			current = rel.FieldSchema
			alias := strings.Join(parts, "__")
			if join.Alias != "" && len(parts) == len(strings.Split(join.Name, ".")) {
				alias = join.Alias
			}
			for _, column := range current.DBNames {
				key := alias + "__" + column
				stmt.ColumnMapping[strings.ToUpper(key)] = key
			}
		}
	}
}
