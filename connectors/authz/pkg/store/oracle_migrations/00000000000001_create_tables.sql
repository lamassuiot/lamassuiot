CREATE TABLE principals (
    id          VARCHAR2(255) PRIMARY KEY,
    name        VARCHAR2(255) NOT NULL,
    description VARCHAR2(1024),
    type        VARCHAR2(64) NOT NULL,
    auth_config JSON,
    active      BOOLEAN DEFAULT TRUE NOT NULL,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX idx_principals_type ON principals(type);
CREATE INDEX idx_principals_active ON principals(active);

CREATE TABLE principal_policies (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    principal_id VARCHAR2(255) NOT NULL REFERENCES principals(id) ON DELETE CASCADE,
    policy_id    VARCHAR2(255) NOT NULL,
    granted_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    granted_by   VARCHAR2(255),
    CONSTRAINT uq_authz_principal_policy UNIQUE (principal_id, policy_id)
);
CREATE INDEX idx_pp_principal ON principal_policies(principal_id);
CREATE INDEX idx_pp_policy ON principal_policies(policy_id);

